-- NIN (National Identification Number) for organization owners, employees and
-- external members. Each record stores the 11-digit NIN, an uploaded NIN
-- document (slip/card image or PDF) and a manual verification status.
--
-- Idempotent: safe to run more than once.

alter table public.organizations
  add column if not exists nin text;
alter table public.organizations
  add column if not exists nin_document_url text;
alter table public.organizations
  add column if not exists nin_status text not null default 'PENDING';

alter table public.employees
  add column if not exists nin text;
alter table public.employees
  add column if not exists nin_document_url text;
alter table public.employees
  add column if not exists nin_status text not null default 'PENDING';

alter table public.members
  add column if not exists nin text;
alter table public.members
  add column if not exists nin_document_url text;
alter table public.members
  add column if not exists nin_status text not null default 'PENDING';

-- Private bucket for uploaded NIN documents. Access is granted through signed
-- URLs generated by the server (see src/app/nin/actions.ts).
insert into storage.buckets (id, name, public)
values ('nin-documents', 'nin-documents', false)
on conflict (id) do update set public = false;
